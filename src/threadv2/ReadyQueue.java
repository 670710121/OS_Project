/**
 * ส่วนติดต่อกลางที่ใช้ร่วมกันระหว่างนโยบายจัดลำดับงานทั้งสองแบบ
 * Worker เรียกใช้งานผ่าน interface นี้ จึงไม่จำเป็นต้องรู้ว่าเลือกนโยบายใดอยู่
 */
public interface ReadyQueue {
    void add(Job job);               // เพิ่มงานใหม่ที่พร้อมทำลงในคิว
    Job take() throws InterruptedException; // รอและคืนงานถัดไป หากปิดระบบและไม่มีงานเหลือให้คืน null
    int size();                      // คืนจำนวนงานที่กำลังรออยู่ในคิว
    void shutdown();                 // แจ้ง Worker ที่กำลังรอว่าจะไม่มีงานใหม่เข้ามาอีก
}
